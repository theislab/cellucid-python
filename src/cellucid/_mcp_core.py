"""
The core of ``cellucid mcp``, without the MCP transport: what one agent
connection lists, which viewer it drives, and what it answers.

Everything an agent sees of Cellucid is the web app's: the tools are the
action catalogue as MCP tools, made by the same function the web connector
uses (``mcp_tools.json``, generated by the web repository's
``scripts/generate-action-catalog.mjs`` from this package's own
``action_catalog.json``), and while a viewer page is open its own list is
used -- the same tools, each saying what the person's permission settings
make of it for this connection. The page runs every call (:mod:`cellucid._agent_link`).
This module only chooses the viewer, names the agent, answers
``cellucid_status`` and says, in one sentence, what is missing when no
viewer can take a call. cellucid-r's ``cellucid_mcp()`` has the same core
(``R/mcp.R``); the shared ``tests/fixtures/local_agents.json`` pins both.
"""

from __future__ import annotations

import contextlib
import hashlib
import itertools
import json
import re
import secrets
import threading
from collections.abc import Callable
from functools import cache
from importlib import resources
from typing import Any

from ._agent_link import (
    AgentsFolderError,
    RemoteViewerLink,
    ViewerLink,
    ViewerUnavailableError,
    describe_record,
    discover_viewers,
    not_open_sentence,
)

#: The version of ``mcp_tools.json`` this package reads.
MCP_TOOLS_SCHEMA = 1

#: What the server calls itself to an agent app.
SERVER_NAME = "cellucid"
SERVER_TITLE = "Cellucid"

#: How long a page may take to list its tools.
LIST_TIMEOUT_SECONDS = 30.0

#: What a call is answered with when no viewer can take it.
NO_VIEWER = (
    "No Cellucid viewer is open on this computer. Ask the person to open their dataset in a viewer "
    "(cellucid mcp --open <file>, or cellucid serve <file>; cellucid.show_anndata(...) in Python; "
    "cellucid::cellucid_view(...) in R), "
    "then try again; cellucid_status says which viewers are found."
)

#: What a viewer chosen by ``--viewer`` that is not found is answered with.
NOT_FOUND = "No Cellucid viewer on this computer is {choice}. cellucid_status lists the viewers found."


class McpToolsDocumentError(RuntimeError):
    """``mcp_tools.json`` is missing, damaged, or of another schema."""


@cache
def mcp_tools_document() -> dict[str, Any]:
    """The generated document: the tools, the instructions, the status tool,
    the app names (checked against the action catalogue it was made from)."""
    package = resources.files("cellucid")
    try:
        text = package.joinpath("mcp_tools.json").read_text(encoding="utf-8")
        catalog = package.joinpath("action_catalog.json").read_bytes()
    except OSError as error:
        raise McpToolsDocumentError(f"This cellucid installation lacks its agent tools: {error}") from error
    document = json.loads(text)
    if type(document) is not dict or document.get("schema") != MCP_TOOLS_SCHEMA:
        raise McpToolsDocumentError("mcp_tools.json is not of the schema this cellucid reads")
    if document["catalogDigest"] != hashlib.sha256(catalog).hexdigest():
        raise McpToolsDocumentError(
            "mcp_tools.json was made from another action catalogue than this cellucid's: reinstall cellucid"
        )
    return document


def agent_name_of(client_name: str | None, client_title: str | None = None) -> str:
    """The agent an app's MCP ``clientInfo`` names, as the viewer shows it:
    its title when it gives one, else the name Cellucid knows it by
    (``claude-code`` is Claude Code), else its name as given, else
    ``Local agent``; on one line (runs of whitespace are one space)."""
    document = mcp_tools_document()
    for candidate in (client_title, document["agentNames"].get(client_name or ""), client_name):
        if isinstance(candidate, str):
            text = " ".join(candidate.split())
            if text:
                return text
    return str(document["agentFallback"])


#: A name ``quote_name`` marked: the data tags around one JSON string with no
#: raw ``<``, newline or unescaped ``"`` in it (``targets/names.js`` ``MARKED_NAME``).
_MARKED = re.compile(r'<cellucid-data>("(?:[^"\\\n<]|\\.)*")</cellucid-data>')


def result_data_text(json_text: str) -> str:
    """JSON as a result's data, as the Cellucid tab writes every result
    (``relay-protocol.js`` ``resultDataText``): between the data tags of
    ``mcp_tools.json`` (``resultData.tags``), every ``<`` written ``\\u003c``,
    so a name written by others in it is data an agent never takes for
    instructions and nothing in it can close the tags."""
    tags = mcp_tools_document()["resultData"]["tags"]
    return str(tags["open"]) + json_text.replace("<", "\\u003c") + str(tags["close"])


def quote_name(name: str) -> str:
    """A name written by others marked as data where the sentence is built, as
    the tab marks every name it quotes (``targets/names.js`` ``quoteName``):
    the data tags of ``mcp_tools.json`` around the name as one JSON string,
    every ``<`` in it written ``\\u003c``, so no name can end its quotes, its
    line or its mark."""
    tags = mcp_tools_document()["resultData"]["tags"]
    return str(tags["open"]) + _js_json(str(name)).replace("<", "\\u003c") + str(tags["close"])


def refusal_text(text: str) -> str:
    """A sentence of this package's as an agent reads it, as the tab sends its
    refusals (``mcp-content.js`` ``refusalText``): the names in it were marked
    where it was built (``quote_name``); every other ``<`` is escaped, so
    nothing else can open or close a mark. Nothing is marked here."""
    parts: list[str] = []
    last = 0
    for match in _MARKED.finditer(text):
        parts.append(text[last:match.start()].replace("<", "\\u003c"))
        parts.append(match.group(0))
        last = match.end()
    parts.append(text[last:].replace("<", "\\u003c"))
    return "".join(parts)


def _js_json(value: Any) -> str:
    """JSON as the web app's ``JSON.stringify`` writes it (no spaces, text as it is)."""
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _tool_error(text: str) -> dict[str, Any]:
    return {"content": [{"type": "text", "text": refusal_text(text)}], "isError": True}


def _matches(record_or_description: dict[str, Any], choice: str) -> bool:
    dataset = record_or_description.get("dataset") or {}
    return choice in {record_or_description.get("viewer"), dataset.get("id"), dataset.get("name")}


class LocalAgentSession:
    """One agent connection (one ``cellucid mcp`` process and its app).

    ``opened`` is the viewer this process serves itself (``--open``), or None;
    ``choice`` names the viewer to drive among those published on this
    computer (its viewer id, dataset id or dataset name), or None for the most
    recently opened one whose page is open (else the most recent).
    ``discover`` lists the published viewers (tests give their own).
    """

    def __init__(
        self,
        *,
        opened: ViewerLink | None = None,
        choice: str | None = None,
        discover: Callable[[], list[dict[str, Any]]] = discover_viewers,
    ) -> None:
        self.connection_id = f"local-{secrets.token_hex(6)}"
        self._client_name: str | None = None
        self.agent = mcp_tools_document()["agentFallback"]
        self._opened = opened
        self._opening: str | None = None
        self._choice = choice
        self._discover = discover
        self._lock = threading.Lock()
        self._link: ViewerLink | None = opened
        self._remote_viewer: str | None = None
        #: Why the agents folder was refused, when it was (its sentence).
        self._folder_error: str | None = None
        self._numbers = itertools.count(1)
        self._tools_listeners: list[Callable[[], None]] = []
        self._remove_link_listener: Callable[[], None] | None = (
            None if opened is None else opened.add_tools_listener(self._tools_changed)
        )

    # -- who is asking ------------------------------------------------------

    def adopt_client(self, name: str | None, title: str | None = None) -> None:
        """The app this connection serves (its ``clientInfo``)."""
        self._client_name = None if name is None else " ".join(name.split()) or None
        self.agent = agent_name_of(name, title)

    @property
    def connection(self) -> dict[str, Any]:
        """The connection as agent commands carry it (``{id, client}``)."""
        return {"id": self.connection_id, "client": self._client_name}

    # -- which viewer ----------------------------------------------------------

    def set_opened(self, link: ViewerLink | None, *, opening: str | None = None) -> None:
        """The viewer this process serves itself, once it started (``--open``);
        ``opening`` says it is still starting (its file), or why it failed."""
        with self._lock:
            if self._remove_link_listener is not None:
                self._remove_link_listener()
                self._remove_link_listener = None
            self._opened = link
            self._opening = opening
            self._link = link
            if link is not None:
                self._remove_link_listener = link.add_tools_listener(self._tools_changed)
        self._tools_changed()

    def link(self) -> ViewerLink | None:
        """The viewer this connection drives now: the one it opened, else one
        published on this computer, found again when the one it had stopped,
        or, when none was named, when its page is not open and another
        viewer's is."""
        with self._lock:
            if self._opened is not None:
                return self._opened
            current = self._link
        if (
            isinstance(current, RemoteViewerLink)
            and current.stopped is None
            and (self._choice is not None or current.connected())
        ):
            return current
        try:
            records = self._discover()
            self._folder_error = None
        except AgentsFolderError as error:
            self._folder_error = str(error)
            records = []
        if self._choice is not None:
            records = [record for record in records if _matches(record, self._choice)]
        chosen = self._choose(records)
        with self._lock:
            if chosen is None:
                self._drop_link_locked()
                return None
            if self._remote_viewer == chosen["viewer"] and self._link is not None:
                return self._link
            self._drop_link_locked()
            link = RemoteViewerLink(chosen, self.connection_id)
            self._link = link
            self._remote_viewer = chosen["viewer"]
            self._remove_link_listener = link.add_tools_listener(self._tools_changed)
        return link

    @staticmethod
    def _choose(records: list[dict[str, Any]]) -> dict[str, Any] | None:
        if not records:
            return None
        # The newest viewer whose page is open; else the newest.
        for record in records:
            if describe_record(record).get("connected"):
                return record
        return records[0]

    def _drop_link_locked(self) -> None:
        if self._remove_link_listener is not None:
            self._remove_link_listener()
            self._remove_link_listener = None
        if self._link is not None and self._link is not self._opened:
            self._link.close()
        self._link = None
        self._remote_viewer = None

    # -- what it lists -----------------------------------------------------

    def add_tools_listener(self, listener: Callable[[], None]) -> None:
        """Hear when the tool list may have changed (send ``tools/list_changed``)."""
        self._tools_listeners.append(listener)

    def _tools_changed(self) -> None:
        for listener in list(self._tools_listeners):
            with contextlib.suppress(Exception):
                listener()

    def tools(self) -> list[dict[str, Any]]:
        """The tools: the open page's list for this connection, else the
        generated one (the person's default settings), and the status tool."""
        document = mcp_tools_document()
        tools: list[dict[str, Any]] = document["tools"]
        link = self.link()
        if link is not None and link.connected():
            with contextlib.suppress(ViewerUnavailableError, TimeoutError, ValueError, OSError):
                tools = link.list_tools(self.connection, LIST_TIMEOUT_SECONDS)
        return [*tools, document["statusTool"]]

    @property
    def instructions(self) -> str:
        return str(mcp_tools_document()["instructions"])

    # -- what it answers ---------------------------------------------------

    def status(self) -> dict[str, Any]:
        """``cellucid_status``: the viewer driven, every viewer found, and what to tell the person."""
        link = self.link()
        driven = None if link is None else link.describe()
        found = []
        try:
            records = self._discover()
        except AgentsFolderError:
            records = []
        for record in records:
            found.append(
                {
                    "viewer": record["viewer"],
                    "runtime": record["runtime"],
                    "dataset": record["dataset"],
                    "url": record["url"],
                    "driven": driven is not None and driven.get("viewer") == record["viewer"],
                }
            )
        if driven is None:
            # Inside the status's data already: the name quoted as JSON, not marked again.
            advice = self._unavailable_sentence(quote=lambda name: json.dumps(name, ensure_ascii=False))
        elif not driven.get("connected"):
            advice = not_open_sentence(driven)
        else:
            advice = None
        return {
            "agent": self.agent,
            "connected": driven is not None and bool(driven.get("connected")),
            "viewer": driven,
            "viewers": found,
            "advice": advice,
        }

    def _unavailable_sentence(self, quote: Callable[[str], str] = quote_name) -> str:
        if self._opening is not None:
            return self._opening
        if self._folder_error is not None:
            return self._folder_error
        if self._choice is not None:
            return NOT_FOUND.format(choice=quote(self._choice))
        return NO_VIEWER

    def status_result(self) -> dict[str, Any]:
        # The viewers' and datasets' names in it were written by others: marked as data, as the tab's results are.
        return {"content": [{"type": "text", "text": result_data_text(_js_json(self.status()))}], "isError": False}

    def next_request_id(self) -> str:
        return f"{self.connection_id}-{next(self._numbers)}"

    def start_call(self, request_id: str, tool: str, args: dict[str, Any], listener: Callable[[str, dict[str, Any]], None]) -> ViewerLink:
        """Send one call to the viewer this connection drives; raise
        :class:`ViewerUnavailableError` with the sentence an agent reads when
        none can take it."""
        link = self.link()
        if link is None:
            raise ViewerUnavailableError(self._unavailable_sentence())
        link.start_call(request_id, tool, args, self.agent, self.connection, listener)
        return link

    def close(self) -> None:
        with self._lock:
            self._drop_link_locked()

    @staticmethod
    def error_result(text: str) -> dict[str, Any]:
        return _tool_error(text)
