"""The Cellucid citation is written once and generated everywhere else.

The preferred-citation block of CITATION.cff is copied from the single source in
theislab/cellucid by ``cellucid-private/scripts/sync_citation.py``, which also
generates the README's citation and the citation on ``docs/citing.md``. Each
generated region records the SHA-256 of the block it came from and of its own
body, so a block changed without re-running the script, or a region edited by
hand, fails here.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

import pytest

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
BLOCK_BEGIN = "# BEGIN cellucid preferred-citation"
BLOCK_END = "# END cellucid preferred-citation"
REGION_BEGIN = re.compile(
    r"(?m)^<!-- BEGIN cellucid-citation \(generated by "
    r"cellucid-private/scripts/sync_citation\.py from CITATION\.cff; do not edit\) "
    r"source-sha256=([0-9a-f]{64}) body-sha256=([0-9a-f]{64}) -->\n"
)
REGION_END = "<!-- END cellucid-citation -->\n"
GENERATED_SURFACES = ("README.md", "docs/citing.md")


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _read(relative: str) -> str:
    return (REPOSITORY_ROOT / relative).read_bytes().decode("utf-8")


def _block() -> str:
    lines = _read("CITATION.cff").splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == BLOCK_BEGIN]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == BLOCK_END]
    assert len(begins) == 1 and len(ends) == 1 and ends[0] > begins[0]
    block = "".join(lines[begins[0] : ends[0] + 1])
    return block if block.endswith("\n") else block + "\n"


def _is_placeholder(block: str) -> bool:
    return re.search(r"(?m)^  doi:", block) is None


def test_citation_cff_carries_the_preferred_citation_block() -> None:
    block = _block()
    assert re.search(r"(?m)^preferred-citation:$", block)
    if _is_placeholder(block):
        assert re.search(r'(?m)^  title: ".*PLACEHOLDER.*"$', block)
        assert re.search(r"(?m)^  (?:year|url):", block) is None


@pytest.mark.parametrize("relative", GENERATED_SURFACES)
def test_generated_citation_matches_citation_cff(relative: str) -> None:
    text = _read(relative)
    begins = list(REGION_BEGIN.finditer(text))
    assert len(begins) == 1, f"{relative} must hold exactly one generated citation region"
    assert text.count(REGION_END) == 1, f"{relative} must hold exactly one region end"
    body = text[begins[0].end() : text.index(REGION_END)]
    block = _block()
    assert begins[0].group(1) == _sha256(block), (
        f"CITATION.cff changed after {relative} was generated; "
        "run cellucid-private/scripts/sync_citation.py"
    )
    assert begins[0].group(2) == _sha256(body), (
        f"the citation region in {relative} was edited by hand; edit "
        "theislab/cellucid/CITATION.cff and run cellucid-private/scripts/sync_citation.py"
    )
    assert ("**Placeholder citation.**" in body) == _is_placeholder(block)

